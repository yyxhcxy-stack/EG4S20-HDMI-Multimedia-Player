def generate_verilog():
    lines = []
    lines.append("// Compact 8x8 font ROM table for ST7735S telemetry副屏")
    lines.append("function [7:0] get_font_byte;")
    lines.append("    input [5:0] char_idx;")
    lines.append("    input [2:0] row;")
    lines.append("    begin")
    lines.append("        case ({char_idx, row})")
    for idx, ch in enumerate(CHARS_ORDER):
        rows = FONT_8X8[ch]
        for r, val in enumerate(rows):
            addr = (idx << 3) | r
            lines.append(f"            9'd{addr}: get_font_byte = 8'h{val:02X}; // '{ch}' row {r}")
    lines.append("            default: get_font_byte = 8'h00;")
    lines.append("        endcase")
    lines.append("    end")
    lines.append("endfunction")
    return "\n".join(lines)

with open("tools/font_table.v", "w", encoding="utf-8") as f:
    f.write(generate_verilog())

print(f"Generated font table with {len(CHARS_ORDER)} characters ({len(CHARS_ORDER)*8} entries).")
