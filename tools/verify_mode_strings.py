def decode_char(c):
    return chr(c)

patterns = {
    "1:IDLE": [0x5B, 0x31, 0x3A, 0x49, 0x44, 0x4C, 0x45, 0x5D],
    "2:SEEK": [0x5B, 0x32, 0x3A, 0x53, 0x45, 0x45, 0x4B, 0x5D],
    "3:RAM ": [0x5B, 0x33, 0x3A, 0x52, 0x41, 0x4D, 0x20, 0x5D],
    "4:3.0S": [0x5B, 0x34, 0x3A, 0x33, 0x2E, 0x30, 0x53, 0x5D],
    "4:MANU": [0x5B, 0x34, 0x3A, 0x4D, 0x41, 0x4E, 0x55, 0x5D],
    "FAIL  ": [0x5B, 0x46, 0x41, 0x49, 0x4C, 0x5D, 0x20, 0x20]
}

for name, codes in patterns.items():
    text = "".join([decode_char(c) for c in codes])
    print(f"{name:<10} -> '{text}' (len={len(text)})")
    assert len(codes) == 8
